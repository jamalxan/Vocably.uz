// Bu skript network yoki TTS'siz, sof PCM matematikasi bilan qisqa (2 soniya)
// neytral ikki-ohangli "chime" WAV yasaydi (440Hz -> 880Hz, fade in/out — click
// tovushisiz) va uni to'g'ridan-to'g'ri `data:audio/wav;base64,...` sifatida
// `src/features/exam/listening/testTone.ts` fayliga yozadi — GridFS'da alohida
// fayl saqlash yoki uni tashuvchi endpoint shart emas, bundle ichida doim bor.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SAMPLE_RATE = 11025;
const DURATION_SEC = 2;
const N = SAMPLE_RATE * DURATION_SEC;

function fadeGain(i, n, fadeSamples) {
  if (i < fadeSamples) return i / fadeSamples;
  if (i > n - fadeSamples) return (n - i) / fadeSamples;
  return 1;
}

const pcm = new Int16Array(N);
const fadeSamples = Math.floor(SAMPLE_RATE * 0.05); // 50ms fade
for (let i = 0; i < N; i++) {
  const t = i / SAMPLE_RATE;
  // Birinchi yarmi 440Hz, ikkinchi yarmi 880Hz — ikkita aniq ohang eshitiladi.
  const freq = t < DURATION_SEC / 2 ? 440 : 880;
  const gain = fadeGain(i, N, fadeSamples) * 0.5; // 0.5 — qattiq bo'lib ketmasin
  pcm[i] = Math.round(Math.sin(2 * Math.PI * freq * t) * gain * 32767);
}

function buildWav(pcmData, sampleRate) {
  const bytesPerSample = 2;
  const dataSize = pcmData.length * bytesPerSample;
  const buffer = Buffer.alloc(44 + dataSize);
  buffer.write('RIFF', 0);
  buffer.writeUInt32LE(36 + dataSize, 4);
  buffer.write('WAVE', 8);
  buffer.write('fmt ', 12);
  buffer.writeUInt32LE(16, 16); // PCM fmt chunk size
  buffer.writeUInt16LE(1, 20); // audio format = PCM
  buffer.writeUInt16LE(1, 22); // channels = mono
  buffer.writeUInt32LE(sampleRate, 24);
  buffer.writeUInt32LE(sampleRate * bytesPerSample, 28); // byte rate
  buffer.writeUInt16LE(bytesPerSample, 32); // block align
  buffer.writeUInt16LE(16, 34); // bits per sample
  buffer.write('data', 36);
  buffer.writeUInt32LE(dataSize, 40);
  for (let i = 0; i < pcmData.length; i++) {
    buffer.writeInt16LE(pcmData[i], 44 + i * bytesPerSample);
  }
  return buffer;
}

const wavBuffer = buildWav(pcm, SAMPLE_RATE);
const base64 = wavBuffer.toString('base64');
const dataUri = `data:audio/wav;base64,${base64}`;

const outPath = path.join(__dirname, '..', '..', 'src', 'features', 'exam', 'listening', 'testTone.ts');
const fileContent = `// AUTO-GENERATED by scripts/tts/gen-test-tone.mjs — do not edit by hand.
// VOCABLY-TZ.md §2.1/§5 item 11 — neutral 2s two-tone (440Hz -> 880Hz) sound
// check sample, used INSTEAD of the real Part 1 exam audio in VolumeCheck.
export const NEUTRAL_TEST_TONE_URL = '${dataUri}';
`;
writeFileSync(outPath, fileContent, 'utf-8');
console.log(`Wrote ${outPath} (${fileContent.length} bytes, wav ${wavBuffer.length} bytes)`);
