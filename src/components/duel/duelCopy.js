/** Error text for the current locale: known code → copy, else the server's message, else generic. */
export const errorText = (c, e) => c.errors[e?.code] || (e instanceof TypeError ? c.errors.network : e?.message && e.message !== 'error' ? e.message : c.error);

export const fill = (s, vars) => String(s).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
export const signed = (n) => (n > 0 ? `+${n}` : String(n));
